-- cadastro mostra o número, o custo não o conta, e nada acusa.
--
-- POR QUE EXISTE: dez verbas formam o custo do prestador além do par 222+228,
-- e nenhuma chegava ao orçado. Achado pelo RH ao conferir o cadastro — "tem
