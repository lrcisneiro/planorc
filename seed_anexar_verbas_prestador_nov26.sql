-- branco; o importador, que apaga o que o arquivo menciona, remove o benefício
-- que a pessoa tinha. Medido em 2026:
--     231 Bônus ........ 107 pessoas no ano · ~48 num mês qualquer
--     235 Bônus compl. .. 36 pessoas no ano · 1 em agosto, 1 em setembro
-- Importar por setembro apagava 35 das 36. **Média mensal não tem esse
-- defeito**: ela não depende de o mês sorteado ser generoso.
--
-- O VALOR é a média de 2026 por pessoa (jan–set, **julho fora** por vir
