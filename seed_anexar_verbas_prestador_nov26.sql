INSERT INTO posto_verba (tenant_id, posto_id, verba_id, valor, ativo)
SELECT (SELECT id FROM t), p.id, v.id, d.valor, true
  FROM dados d
  JOIN posto p ON p.codigo = d.posto_cod AND p.tenant_id = (SELECT id FROM t)
  JOIN verba_folha v ON v.codigo = d.verba_cod AND v.tenant_id = (SELECT id FROM t)
 WHERE v.tipo_calculo = 'VALOR_FIXO'   -- ⚠ guarda: verba ainda INFORMATIVA não entra calada
ON CONFLICT (posto_id, verba_id) DO UPDATE SET valor = EXCLUDED.valor, ativo = true;

-- ---------------- conferência ----------------
SELECT 'verbas variáveis anexadas' AS secao,
       (SELECT count(*)::text || ' par(es) · R$ ' || round(sum(pv.valor),2)::text || '/mês'
          FROM posto_verba pv JOIN verba_folha v ON v.id=pv.verba_id
         WHERE pv.ativo AND v.codigo IN ('168','223','224','230','231','234','235','236','237','418')) AS resultado
UNION ALL
SELECT 'por verba',
       (SELECT string_agg(t, ' · ') FROM (
          SELECT v.codigo || '=' || count(*)::text AS t
            FROM posto_verba pv JOIN verba_folha v ON v.id=pv.verba_id
           WHERE pv.ativo AND v.codigo IN ('168','223','224','230','231','234','235','236','237','418')
           GROUP BY v.codigo ORDER BY v.codigo) q)
UNION ALL
SELECT 'alguma ficou de fora por ser INFORMATIVA?',
       (SELECT CASE WHEN count(*)=0 THEN 'nenhuma — correto'
                    ELSE '⛔ rode o seed de verbas antes: ' || string_agg(codigo,', ') END
          FROM verba_folha WHERE ativo AND tipo_calculo='INFORMATIVA'
            AND codigo IN ('168','223','224','230','231','234','235','236','237','418'))
UNION ALL
SELECT 'benefícios que NÃO foram tocados (continuam)',
       (SELECT string_agg(t, ' · ') FROM (
          SELECT v.codigo || '=' || count(*)::text AS t
            FROM posto_verba pv JOIN verba_folha v ON v.id=pv.verba_id
           WHERE pv.ativo AND v.codigo IN ('D49','A76','D50','A15','A51','063')
           GROUP BY v.codigo ORDER BY v.codigo) q);
