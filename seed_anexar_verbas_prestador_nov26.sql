-- Para quem trabalhou o período inteiro as duas contas dão o mesmo (0,7% de
-- diferença); a distância toda vem de quem entrou ou saiu no meio, e para
-- esses o que se orça é o mês em que trabalham.
--
-- ⚠ NÃO TOCA EM MAIS NADA. Só `posto_verba`. Nem salário, nem vigência, nem
-- `fte` — de propósito: o importador de postos escreve `admissao`, `ini_ano`,
-- `ini_mes` e `fte` mesmo quando o arquivo não os traz, e 322 dos 327 postos
-- ativos têm esses campos preenchidos. Carregar isto por arquivo apagaria a
-- vigência de 193 pessoas, e vigência nula faz o motor orçar os 12 meses.
--
-- ⚠ 16 postos ficam de fora: não têm nada no `srd` de 2026 — os sócios e o
-- pró-labore, que não passam pelo arquivo de movimento.
--
-- ⚠ O valor SUBSTITUI o que estiver lá (`DO UPDATE`). É o objetivo: a 230 e a
-- 231 têm hoje o valor de um mês, e é isso que se está corrigindo. Valor
-- digitado à mão nessas dez verbas se perde.
