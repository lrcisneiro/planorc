-- Só códigos que aparecem UMA vez no arquivo: código repetido é ambíguo, e
-- escolher por ordem de leitura é decidir no escuro.
INSERT INTO cargo_step (tenant_id, cargo_id, step, codigo)
SELECT c.tenant_id, c.id, s.step, s.codigo
  FROM _st s
  JOIN cargo c ON upper(c.nome) = s.cargo_nome AND c.origem = 'PLANO'
 WHERE (SELECT count(*) FROM _st d WHERE d.codigo = s.codigo) = 1
ON CONFLICT (tenant_id, codigo) DO NOTHING;

SELECT 'steps carregados' AS secao, count(*)::text AS resultado FROM cargo_step
UNION ALL SELECT 'cargos com step', (SELECT count(DISTINCT cargo_id)::text FROM cargo_step)
UNION ALL SELECT 'áreas (prefixo) distintas', (SELECT count(DISTINCT grupo)::text FROM cargo_step)
UNION ALL SELECT 'cargos em mais de uma área',
  (SELECT count(*)::text FROM (SELECT cargo_id FROM cargo_step
      GROUP BY cargo_id HAVING count(DISTINCT grupo) > 1) x)
UNION ALL SELECT '⚠ códigos repetidos no arquivo — NÃO carregados, devolver ao RH',
  (SELECT coalesce(string_agg(DISTINCT codigo, ', ' ORDER BY codigo), 'nenhum')
     FROM _st s WHERE (SELECT count(*) FROM _st d WHERE d.codigo = s.codigo) > 1)
UNION ALL SELECT 'steps do arquivo sem cargo correspondente',
  (SELECT count(*)::text FROM _st s WHERE NOT EXISTS (
     SELECT 1 FROM cargo c WHERE upper(c.nome) = s.cargo_nome AND c.origem = 'PLANO'))
UNION ALL SELECT 'cargo_step_id em posto_v',
  CASE WHEN EXISTS (SELECT 1 FROM information_schema.columns
                     WHERE table_name='posto_v' AND column_name='cargo_step_id')
       THEN 'sim' ELSE 'AINDA NAO — a v3_159 recria a view' END;
