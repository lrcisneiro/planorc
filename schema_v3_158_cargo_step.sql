-- ============================================================
-- v3_158 — STEP é filho do cargo, e é o elo com o ERP
--
-- Eu tratei o STEP como ruído na v3_156 — "faixa salarial, não cargo" — e
-- estava certo sobre o que ele É e errado sobre o que ele SERVE: o código
-- completo é o identificador que o ERP usa. Sem ele não há conciliação possível
-- quando a integração chegar.
--
-- Por isso STEP vira FILHO do cargo, não um cargo. Os 190 cargos-base
-- continuam servindo para agrupar e visualizar; os steps carregam o código.
--
-- ⚠ O CÓDIGO É (ÁREA, CARGO, STEP) — não (cargo, step). Descobri isso levando
-- um `duplicate key` na cara: `UNIQUE (cargo_id, step)` afirma que um cargo tem
-- UM step 1, e `AUXILIAR ADMINISTRATIVO` tem SEIS — um por área (12 adm/fin,
-- 13 contábil, 14 gente, 45, 46, 47), cada uma com seu bloco de quatro códigos.
-- 26 dos 190 cargos se repetem assim. Eu li o prefixo de dois dígitos como
-- enfeite do número quando ele é a terceira dimensão da chave. Por isso a única
-- chave natural aqui é o `codigo` inteiro, e `(cargo_id, step)` NÃO é única.
-- `grupo` é coluna gerada do prefixo: derivada, nunca digitada, não desgarra.
-- Ainda NÃO liga a `area_funcional` — o de-para prefixo→área é outra conversa.
--
-- ⚠ 17 códigos vêm REPETIDOS da planilha, com cargos diferentes (o rabo do
-- bloco 43 foi digitado com prefixo 44, e 42064-42071 servem a dois cargos
-- cada). Esses NÃO entram: `ON CONFLICT DO NOTHING` deixaria o primeiro ganhar
-- em silêncio, que é a armadilha da v3_157 de novo. Entram os 923 inequívocos,
-- e o SELECT final lista os 17 para voltarem ao RH.
--
-- `posto.cargo_step_id` fica NULO por enquanto: o step de cada pessoa vem do
-- ERP. O que esta migration entrega é o lugar onde ele cabe.
--
-- ⚠ Coluna nova em `posto` tem DUAS pontas (v3_147/148): entra em `posto_v` no
-- FIM (v3_159) e ganha GRANT próprio.
--
-- Termina em SELECT.
-- ============================================================

CREATE TABLE IF NOT EXISTS cargo_step (
  id        uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id uuid NOT NULL REFERENCES tenant(id) ON DELETE CASCADE,
  cargo_id  uuid NOT NULL REFERENCES cargo(id) ON DELETE CASCADE,
  step      smallint NOT NULL,
  codigo    text NOT NULL,
  grupo     text GENERATED ALWAYS AS (left(codigo, 2)) STORED,
  ativo     boolean NOT NULL DEFAULT true,
  UNIQUE (tenant_id, codigo)
);
-- Defensivo: se uma tentativa anterior deixou o unique errado de pé, sai.
ALTER TABLE cargo_step DROP CONSTRAINT IF EXISTS cargo_step_cargo_id_step_key;
CREATE INDEX IF NOT EXISTS idx_cargo_step_cargo ON cargo_step (cargo_id);

ALTER TABLE cargo_step ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS cargo_step_sel ON cargo_step;
CREATE POLICY cargo_step_sel ON cargo_step FOR SELECT TO authenticated
  USING (tenant_id = (SELECT current_tenant_id()));
DROP POLICY IF EXISTS cargo_step_ins ON cargo_step;
CREATE POLICY cargo_step_ins ON cargo_step FOR INSERT TO authenticated
  WITH CHECK (tenant_id = (SELECT current_tenant_id()) AND (SELECT pode_escrever()));
DROP POLICY IF EXISTS cargo_step_upd ON cargo_step;
CREATE POLICY cargo_step_upd ON cargo_step FOR UPDATE TO authenticated
  USING (tenant_id = (SELECT current_tenant_id()) AND (SELECT pode_escrever()));
DROP POLICY IF EXISTS cargo_step_del ON cargo_step;
CREATE POLICY cargo_step_del ON cargo_step FOR DELETE TO authenticated
  USING (tenant_id = (SELECT current_tenant_id()) AND (SELECT pode_escrever()));

ALTER TABLE posto ADD COLUMN IF NOT EXISTS cargo_step_id uuid REFERENCES cargo_step(id) ON DELETE SET NULL;
GRANT SELECT (cargo_step_id) ON posto TO authenticated;

