-- Cadastros > Cargos, que é decisão de quem desenha, não da carga.
--
-- ⚠ STEP fica de fora. A planilha analítica tem 957 linhas = cargo x STEP, mas
-- STEP é faixa salarial, não cargo: criar 957 registros encheria o catálogo de
-- variações do mesmo trabalho. Se um dia precisar, é coluna em `cargo`.
--
-- `nivel` = nível de carreira do arquivo, mapeado em escala comparável entre
-- ramos: aprendiz 1 ... diretor executivo 11. Só os 96 em uso têm nível; os
-- demais vêm do catálogo sem essa informação.
--
-- Idempotente: `ON CONFLICT` por (tenant, codigo) só atualiza nome e nível.
